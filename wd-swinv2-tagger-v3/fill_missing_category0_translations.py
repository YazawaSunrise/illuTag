def output_dir() -> Path:
    return next(
        p
        for p in ROOT.iterdir()
        if p.is_dir() and p.name.encode("unicode_escape").decode("ascii") == "\\u5168\\u91cf\\u7ffb\\u8bd1"
    )


def split_tag(tag: str) -> list[str]:
    tag = re.sub(r"\([^)]*\)", "", tag)
    tag = tag.replace("another's", "another").replace("own's", "own")
    tag = tag.replace("'", "")
    return [part for part in re.split(r"[_\\-]+", tag) if part]


def join_zh(parts: list[str]) -> str:
    text = "".join(parts)
    text = text.replace("透过", "透视")
    text = text.replace("双色调", "双色")
    text = text.replace("下牙齿仅", "仅露下牙")
    return text


def translate_generic(tag: str) -> str:
    if tag in FULL_TAGS:
        return FULL_TAGS[tag]
    if tag in PHRASE_ZH:
        return PHRASE_ZH[tag]

    parts = split_tag(tag)
    base = "_".join(parts)

    if base in PHRASE_ZH:
        return PHRASE_ZH[base]

    if len(parts) >= 3 and parts[0] == "blood" and parts[1] == "on":
        return translate_generic("_".join(parts[2:])) + "上的血"
    if len(parts) >= 3 and parts[0] in {"scar", "mole", "bandaid"} and parts[1] == "on":
        noun = {"scar": "伤疤", "mole": "痣", "bandaid": "创可贴"}[parts[0]]
        return translate_generic("_".join(parts[2:])) + "上的" + noun
    if len(parts) >= 3 and parts[0] == "hand" and parts[1] == "on":
        return "手放在" + translate_generic("_".join(parts[2:])) + "上"
    if len(parts) >= 3 and parts[0] == "looking" and parts[1] == "at":
        return "看向" + translate_generic("_".join(parts[2:]))
    if len(parts) >= 3 and parts[0] == "finger" and parts[1] == "to":
        return "手指抵着" + translate_generic("_".join(parts[2:]))
    if len(parts) >= 3 and parts[0] == "food" and parts[1] == "on":
        return translate_generic("_".join(parts[2:])) + "上的食物"
    if len(parts) >= 2 and parts[0] == "holding":
        return "拿着" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "unworn":
        return "未穿戴的" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "torn":
        return "破损的" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "frilled":
        return "褶边" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "striped":
        return "条纹" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "print":
        return "印花" + translate_generic("_".join(parts[1:]))
    if len(parts) >= 2 and parts[0] == "vertical" and parts[1] == "striped":
        return "竖条纹" + translate_generic("_".join(parts[2:]))
    if len(parts) >= 2 and parts[0] == "two" and parts[1] == "tone":
        return "双色" + translate_generic("_".join(parts[2:]))
    if len(parts) >= 2 and parts[0] == "see" and parts[1] == "through":
        return "透视" + translate_generic("_".join(parts[2:]))
    if len(parts) >= 2 and parts[-2:] == ["hair", "ornament"]:
        return translate_generic("_".join(parts[:-2])) + "发饰"
    if len(parts) >= 2 and parts[-1] == "bow":
        return translate_generic("_".join(parts[:-1])) + "蝴蝶结"
    if len(parts) >= 3 and parts[-2] == "shaped":
        return translate_generic("_".join(parts[:-2])) + "形" + translate_generic(parts[-1])
    if len(parts) >= 3 and "under" in parts:
        idx = parts.index("under")
        return translate_generic("_".join(parts[:idx])) + "在" + translate_generic("_".join(parts[idx + 1 :])) + "下"
    if len(parts) >= 3 and "around" in parts:
        idx = parts.index("around")
        return translate_generic("_".join(parts[:idx])) + "围在" + translate_generic("_".join(parts[idx + 1 :])) + "周围"
    if len(parts) >= 3 and parts[0] == "on":
        return "在" + translate_generic("_".join(parts[1:])) + "上"

    translated = [TOKEN_ZH.get(part, part) for part in parts]
    return join_zh(translated)


def read_csv(path: Path) -> tuple[list[dict[str, str]], list[str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        return list(reader), list(reader.fieldnames or [])


def write_csv(path: Path, rows: list[dict[str, str]], fields: list[str]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    folder = output_dir()
    path = folder / TARGET_FILE
    rows, fields = read_csv(path)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = folder / f"selected_tags_full_translation_before_category0_fill_{timestamp}.csv"
    shutil.copy2(path, backup)

    filled = 0
    for row in rows:
        if row["category"] != "0":
            continue
        if row["zh_name"].strip() and row.get("source") != "assistant_category0_draft":
            continue
        tag = row["name"]
        row["zh_name"] = translate_generic(tag)
        row["confidence"] = "\u5f85\u6821\u5bf9"
        row["source"] = "assistant_category0_draft"
        old_note = row.get("note", "").strip()
        draft_note = "\u673a\u5668\u8349\u8bd1\uff0c\u9700\u4eba\u5de5\u6821\u5bf9"
        row["note"] = draft_note if not old_note else old_note + "\uff1b" + draft_note
        filled += 1

    write_csv(path, rows, fields)

    review = [r for r in rows if r.get("zh_name_2")]
    missing = [r for r in rows if not r.get("zh_name")]
    category0_draft = [r for r in rows if r.get("source") == "assistant_category0_draft"]
    write_csv(folder / "selected_tags_full_translation_zh_name_2_review.csv", review, fields)
    write_csv(folder / "selected_tags_full_translation_missing_zh.csv", missing, fields)
    write_csv(folder / "selected_tags_full_translation_category0_draft_review.csv", category0_draft, fields)

    print(f"backup={backup}")
    print(f"filled={filled}")
    print(f"remaining_blank={len(missing)}")
    print(f"category0_draft_review={len(category0_draft)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
